#!/bin/sh
# gen-exclusions, pinned: the runet fragment builder.
#
# The generator splices the embedded domain preset and the parsed RIPE
# country-resource-list into one TOML fragment: `exclusions = [` then
# one quoted rule per line, no trailing comma on the last entry, no
# comments inside the array. IPv4 range entries (a.b.c.d-e.f.g.h) expand
# into the aligned CIDR blocks; junk entries are skipped with a warning
# to stderr; the cyrillic 'рф' entries stay out of the preset (the core
# rejects non-ASCII domains). Everything runs offline through
# --from-json against a compact single-line response fixture.
. "$(dirname "$0")/lib.sh"

GEN_EXCL=scripts/gen-runet-exclusions.sh

# count_occ <needle> <text> — prints how many times the needle appears
# (same helper as in test_gen_config.sh; defined here because the file
# is runnable standalone).
count_occ() {
    _needle=$1
    _text=$2
    _n=0
    while :; do
        case $_text in
            *"$_needle"*)
                _n=$((_n + 1))
                _text=${_text#*"$_needle"}
                ;;
            *) break ;;
        esac
    done
    printf '%s\n' "$_n"
}

fixture=$TT_TEST_TMP/ripe.json
printf '{"messages":[],"data":{"resource":"RU","resources":{"ipv4":["203.0.113.0/24","198.51.100.5-198.51.100.8","10.0.0.0-9.9.9.9","not-an-ip"],"ipv6":["2001:db8::/48","2001:db9:1-2::/48"]}}}\n' > "$fixture"

out=$TT_TEST_TMP/exclusions.toml
gen_err=$(sh "$GEN_EXCL" --from-json "$fixture" -o "$out" 2>&1 >/dev/null)

assert_contains "$(cat "$out")" 'exclusions = [' "the fragment opens with the array header"
assert_contains "$(cat "$out")" '"203.0.113.0/24"' "plain CIDR entries pass through"
assert_contains "$(cat "$out")" '"198.51.100.5/32"' "a range starts with the unaligned remainder block"
assert_contains "$(cat "$out")" '"198.51.100.6/31"' "the range expansion continues with the next block"
assert_contains "$(cat "$out")" '"198.51.100.8/32"' "the range expansion ends with the remainder"
assert_contains "$(cat "$out")" '"ya.ru"' "the embedded domain preset lands in the fragment"
assert_contains "$(cat "$out")" '"yandex.ru"' "the preset covers the ru TLD wildcards"
assert_eq "0" "$(grep -c 'рф' "$out")" "the cyrillic рф entries stay out of the preset"
assert_eq "0" "$(count_occ '10.0.0.0' "$out")" "a descending range is skipped"
assert_eq "0" "$(count_occ 'not-an-ip' "$out")" "an unrecognized entry is skipped"
assert_eq "0" "$(count_occ '2001:db9' "$out")" "an ipv6 range is skipped as unsupported"
assert_contains "$(cat "$out")" '"2001:db8::/48"' "ipv6 CIDR entries pass through"
assert_contains "$gen_err" "skipped bad range" "the descending range warning names the entry"
assert_contains "$gen_err" "skipped unrecognized ipv4 entry" "the junk entry warning names the entry"
assert_contains "$gen_err" "skipped ipv6 range" "the ipv6 range warning names the entry"

# The last rule line carries no trailing comma (strict TOML, no reliance
# on the lenient trailing-comma forms).
last_rule=$(grep '^    "' "$out" | tail -1)
case $last_rule in
    *",") _tt_fail "the last rule line has no trailing comma" ;;
    *) _tt_pass "the last rule line has no trailing comma" ;;
esac

# No comments inside the array: the header stays above it.
assert_eq "1" "$(count_occ '# Generated by' "$(cat "$out")")" "the header comment appears once, above the array"

# A missing cached file is an error.
assert_exit 1 "a missing --from-json file fails" sh "$GEN_EXCL" --from-json "$TT_TEST_TMP/nope.json" -o "$out"

tt_test_summary
